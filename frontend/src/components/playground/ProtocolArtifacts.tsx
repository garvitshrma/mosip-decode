import { useState } from "react";
import { Copy, QrCode } from "lucide-react";
import { QRCodeSVG } from "qrcode.react";
import type { Step } from "@playground/shared";

function responseBody(step: Step | undefined): Record<string, unknown> | undefined {
  const body = step?.response?.body;
  if (!body || typeof body !== "object" || Array.isArray(body)) return undefined;
  return body as Record<string, unknown>;
}

function stringField(body: Record<string, unknown> | undefined, key: string): string | undefined {
  const value = body?.[key];
  return typeof value === "string" && value ? value : undefined;
}

/**
 * The offer and presentation request are real protocol artifacts generated by
 * the local stack. They are not resolvable by an external wallet because the
 * local demo never opens a socket; the QR is shown so the flow is demonstrable
 * and so a live adapter can reuse this panel unchanged.
 */
export function ProtocolArtifacts({ steps }: { steps: Step[] }) {
  const [copied, setCopied] = useState<string | null>(null);

  const offerUri = stringField(
    responseBody(steps.find((step) => step.name === "credential_offer")),
    "credential_offer_uri",
  );
  const requestUri = stringField(
    responseBody(steps.find((step) => step.name === "authorization_request")),
    "requestUri",
  );

  if (!offerUri && !requestUri) return null;

  const copy = async (label: string, value: string) => {
    try {
      await navigator.clipboard.writeText(value);
      setCopied(label);
      setTimeout(() => setCopied(null), 1500);
    } catch {
      // The URI stays visible for manual copying when clipboard access is blocked.
    }
  };

  const artifacts = [
    { label: "Credential offer", uri: offerUri },
    { label: "Presentation request", uri: requestUri },
  ].filter((artifact): artifact is { label: string; uri: string } => Boolean(artifact.uri));

  return (
    <section className="artifact-panel">
      <div className="artifact-head">
        <QrCode size={18} />
        <h2>Protocol artifacts</h2>
        <span>QR-ready offer and request URIs</span>
      </div>
      <p className="selector-note">
        These are real URIs from the local reference exchange. An external Inji wallet is not connected
        to <code>local.demo</code>, so the QR is a visual protocol artifact, not a live wallet handoff.
      </p>
      <div className="artifact-grid">
        {artifacts.map((artifact) => (
          <div className="artifact-card" key={artifact.label}>
            <div className="qr-wrap">
              <QRCodeSVG value={artifact.uri} size={136} bgColor="#ffffff" fgColor="#101d45" />
            </div>
            <div className="artifact-copy">
              <strong>{artifact.label}</strong>
              <code>{artifact.uri}</code>
              <button className="secondary-btn small" onClick={() => void copy(artifact.label, artifact.uri)}>
                <Copy size={14} /> {copied === artifact.label ? "Copied" : "Copy URI"}
              </button>
            </div>
          </div>
        ))}
      </div>
    </section>
  );
}
